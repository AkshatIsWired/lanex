#!/usr/bin/env bash
# Regenerates the appliance's Python lock: windows/setup/requirements.lock
# (every package pinned by version and SHA-256, used by Windows Setup with
# pip --require-hashes) and windows/setup/constraints.txt (the same versions
# without hashes, for pip installs on Linux).
#
# Run it as root inside a throwaway Ubuntu 24.04 WSL distro (Python 3.12, the
# appliance's interpreter), from the repository root:
#   wsl -d <build-distro> -u root -- bash windows/setup/make-lock.sh
# Only when deliberately updating dependencies: Setup installs exactly this set.
set -euo pipefail
HERE="$(cd "$(dirname "$0")" && pwd)"
export DEBIAN_FRONTEND=noninteractive
if ! dpkg -s python3-venv >/dev/null 2>&1; then
    apt-get update -qq
    apt-get install -y -qq python3-venv >/dev/null
fi
python3 -c 'import sys; assert sys.version_info[:2] == (3, 12), sys.version'
TOOL=/opt/lanex-locktool
[ -x "$TOOL/bin/uv" ] || { python3 -m venv "$TOOL"; "$TOOL/bin/pip" install -q 'uv==0.9.5'; }
WORK="$(mktemp -d)"
cat > "$WORK/requirements.in" <<'EOF'
librelane==3.0.4
ciel==2.6.1
EOF
"$TOOL/bin/uv" pip compile "$WORK/requirements.in" \
    --python-version 3.12 --python-platform x86_64-manylinux_2_39 \
    --generate-hashes --no-header --index-url https://pypi.org/simple \
    -o "$WORK/requirements.lock"
{
    echo "# LanEx appliance Python lock (Windows Setup). Generated by make-lock.sh"
    echo "# on $(date -u +%Y-%m-%d) for Python 3.12 / Ubuntu 24.04 x86_64."
    echo "# Installed with: pip install --require-hashes --no-deps -r requirements.lock"
    cat "$WORK/requirements.lock"
} > "$HERE/requirements.lock"
{
    echo "# Exact versions of the appliance's Python dependencies (no hashes), from"
    echo "# requirements.lock. For pip installs on Linux:  pip install -c constraints.txt lanex"
    grep -E '^[A-Za-z0-9_.-]+==' "$WORK/requirements.lock" | sed -E 's/ *\\$//'
} > "$HERE/constraints.txt"
rm -rf "$WORK"
grep -c '^[A-Za-z0-9_.-]*==' "$HERE/constraints.txt"
